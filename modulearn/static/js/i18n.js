  function trimParts(value) {
    const leading = (value.match(/^\s*/) || [''])[0];
    const trailing = (value.match(/\s*$/) || [''])[0];
    const core = value.slice(leading.length, value.length - trailing.length).replace(/\s+/g, ' ');
    return { leading, core, trailing };
  }

  function translateCore(core) {
    if (!core || language === 'en') {
      return core;
    }
    if (Object.prototype.hasOwnProperty.call(catalog, core)) {
      return catalog[core];
    }
    const colonMatch = core.match(/^(:\s*)(.+)$/);
    if (colonMatch) {
      const translatedRest = translateCore(colonMatch[2]);
      if (translatedRest !== colonMatch[2]) {
        return colonMatch[1] + translatedRest;
      }
    }
    if (language === 'es') {
      const ofStudentsMatch = core.match(/^(\d+)\s+of\s+(\d+)\s+students$/);
      if (ofStudentsMatch) {
        return `${ofStudentsMatch[1]} de ${ofStudentsMatch[2]} estudiantes`;
      }
      const meanActivitiesMatch = core.match(/^Mean\s+(\d+)%\s+-\s+(\d+)\s+activities$/);
      if (meanActivitiesMatch) {
        return `Media ${meanActivitiesMatch[1]}% - ${meanActivitiesMatch[2]} actividades`;
      }
      const courseNumberMatch = core.match(/^Course\s+(.+)$/);
      if (courseNumberMatch) {
        return `Curso ${courseNumberMatch[1]}`;
      }
      const unitNumberMatch = core.match(/^Unit\s+(.+)$/);
      if (unitNumberMatch) {
        return `Unidad ${unitNumberMatch[1]}`;
      }
      const conditionValueMatch = core.match(/^Condition\s+(.+)$/);
      if (conditionValueMatch) {
        return `Condición ${conditionValueMatch[1]}`;
      }
      const conditionStatusMatch = core.match(/^Condition:\s+(.+)\s+·\s+Status:\s+(.+)$/);
      if (conditionStatusMatch) {
        return `Condición: ${translateCore(conditionStatusMatch[1])} · Estado: ${translateCore(conditionStatusMatch[2])}`;
      }
      const questionTypeMatch = core.match(/^Q(\d*):\s+(.+)$/);
      if (questionTypeMatch) {
        return `P${questionTypeMatch[1]}: ${translateCore(questionTypeMatch[2])}`;
      }
      const createdSessionMatch = core.match(/^Successfully enrolled\s+(\d+)\s+students\.$/);
      if (createdSessionMatch) {
        return `Se inscribieron correctamente ${createdSessionMatch[1]} estudiantes.`;
      }
      const studentDetailsMatch = core.match(/^Student Details:\s+(.+)$/);
      if (studentDetailsMatch) {
        return `Detalles del estudiante: ${studentDetailsMatch[1]}`;
      }
      const successPercentMatch = core.match(/^(\d+)%\s+success$/);
      if (successPercentMatch) {
        return `${successPercentMatch[1]}% éxito`;
      }
      const averagePercentMatch = core.match(/^(\d+)%\s+average$/);
      if (averagePercentMatch) {
        return `${averagePercentMatch[1]}% promedio`;
      }
      const averageProgressAriaMatch = core.match(/^(\d+)\s+percent average progress$/);
      if (averageProgressAriaMatch) {
        return `${averageProgressAriaMatch[1]} por ciento de progreso promedio`;
      }
      const activityCellsMatch = core.match(/^(\d+)%\s+of topic-resource cells have activity, but average completion is\s+(\d+)%\.\s+Students are touching the course broadly without finishing much yet; the drill-downs below can separate exploration from stuck work\.$/);
      if (activityCellsMatch) {
        return `${activityCellsMatch[1]}% de las celdas tema-recurso tienen actividad, pero la finalización promedio es ${activityCellsMatch[2]}%. Los estudiantes están explorando ampliamente el curso sin completar mucho todavía; los desgloses de abajo pueden separar exploración de trabajo atascado.`;
      }
      const behindPatternMatch = core.match(/^(\d+)%\s+of learners are behind the active class pattern\.\s+Treat the flag as a triage queue and sort into the most uneven topic-resource cells below\.$/);
      if (behindPatternMatch) {
        return `${behindPatternMatch[1]}% de los estudiantes están detrás del patrón activo de la clase. Trata la alerta como una cola de triaje y ordena las celdas tema-recurso más desiguales de abajo.`;
      }
      const movingPatternMatch = core.match(/^The class is broadly moving through the material:\s+(\d+)% average completion with\s+(\d+)% engagement\.\s+Look for low-completion cells and students with stale activity\.$/);
      if (movingPatternMatch) {
        return `La clase avanza ampliamente por el material: ${movingPatternMatch[1]}% de finalización promedio con ${movingPatternMatch[2]}% de participación. Busca celdas con baja finalización y estudiantes con actividad desactualizada.`;
      }
      const engagementPatternMatch = core.match(/^Engagement is\s+(\d+)% and progress is\s+(\d+)%\.\s+Use the cell status counts and per-student resource profiles to identify where effort is concentrated\.$/);
      if (engagementPatternMatch) {
        return `La participación es ${engagementPatternMatch[1]}% y el progreso es ${engagementPatternMatch[2]}%. Usa los conteos de estado de celda y los perfiles de recursos por estudiante para identificar dónde se concentra el esfuerzo.`;
      }
    }
    const numericMatch = core.match(/^(\d+)\s+(.+)$/);
    if (numericMatch && Object.prototype.hasOwnProperty.call(numericSuffixCatalog, numericMatch[2])) {
      return numericMatch[1] + ' ' + numericSuffixCatalog[numericMatch[2]];
    }
    let translated = core;
    for (const sourcePrefix of Object.keys(prefixCatalog)) {
      if (translated === sourcePrefix) {
        translated = prefixCatalog[sourcePrefix];
        break;
      }
      if (translated.startsWith(sourcePrefix + ' ')) {
        translated = prefixCatalog[sourcePrefix] + translated.slice(sourcePrefix.length);
        break;
      }
    }
    for (const sourceFragment of Object.keys(fragmentCatalog)) {
      if (translated.includes(sourceFragment)) {
        translated = translated.split(sourceFragment).join(fragmentCatalog[sourceFragment]);
      }
    }
    return translated;
  }

  function translateString(value) {
    if (!value || language === 'en') {
      return value;
    }
    const parts = trimParts(String(value));
    const translated = translateCore(parts.core);
    if (translated === parts.core) {
      return value;
    }
    return parts.leading + translated + parts.trailing;
  }

  function translateTextNode(node) {
    if (!node.nodeValue || !node.nodeValue.trim()) {
      return;
    }
    const parent = node.parentElement;
    if (!parent || parent.closest(textSkipSelector)) {
      return;
    }
    const translated = translateString(node.nodeValue);
    if (translated !== node.nodeValue) {
      node.nodeValue = translated;
    }
  }

  function translateAttributes(element) {
    if (!element || element.nodeType !== 1 || element.closest(attributeSkipSelector)) {
      return;
    }
    attributes.forEach(function (attribute) {
      if (!element.hasAttribute(attribute)) {
        return;
      }
      const value = element.getAttribute(attribute);
      const translated = translateString(value);
      if (translated !== value) {
        element.setAttribute(attribute, translated);
      }
    });
  }

  function translateTree(root) {
    if (language === 'en' || !root || isTranslating) {
      return;
    }
    isTranslating = true;
    try {
      if (root.nodeType === Node.TEXT_NODE) {
        translateTextNode(root);
      } else if (root.nodeType === Node.ELEMENT_NODE || root.nodeType === Node.DOCUMENT_NODE) {
        if (root.nodeType === Node.ELEMENT_NODE) {
          translateAttributes(root);
        }
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
          acceptNode: function (node) {
            const parent = node.parentElement;
            if (!node.nodeValue || !node.nodeValue.trim() || !parent || parent.closest(textSkipSelector)) {
              return NodeFilter.FILTER_REJECT;
            }
            return NodeFilter.FILTER_ACCEPT;
          }
        });
        const nodes = [];
        while (walker.nextNode()) {
          nodes.push(walker.currentNode);
        }
        nodes.forEach(translateTextNode);
        root.querySelectorAll && root.querySelectorAll('*').forEach(translateAttributes);
      }
      document.title = translateString(document.title);
    } finally {
      isTranslating = false;
    }
  }

